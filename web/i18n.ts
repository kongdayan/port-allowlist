export type MessageKey = keyof typeof messages;
export function interpolate(text: string, params: Record<string, string | number> = {}) {
  return text.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? `{${key}}`));
}
export function translate(
  locale: Locale,
  key: MessageKey,
  params?: Record<string, string | number>,
): string {
  return interpolate(messages[key][locale === 'zh-CN' ? 1 : 0], params);
}
export function errorText(
  locale: Locale,
  code: string,
  params?: Record<string, string | number>,
): string {
  return interpolate(
    (errorMessages[code as ErrorCode] || errorMessages.SERVICE_UNAVAILABLE)[locale],
    params,
  );
}
export const dateText = (locale: Locale, at: number, timeZone = 'Asia/Shanghai') =>
  at
    ? new Intl.DateTimeFormat(locale, {
        dateStyle: 'medium',
        timeStyle: 'short',
        hour12: false,
        timeZone,
      }).format(at * 1000)
    : '—';
export const clockText = (locale: Locale, at: number, timeZone = 'Asia/Shanghai') =>
  new Intl.DateTimeFormat(locale, {
    hour: '2-digit',
    minute: '2-digit',
    hour12: false,
    timeZone,
  }).format(at * 1000);
export function bytes(value: number, locale: Locale) {
  const n = Number(value) || 0,
    units = ['B', 'KB', 'MB', 'GB'];
  const index = n > 0 ? Math.min(3, Math.floor(Math.log(n) / Math.log(1024))) : 0;
  return (
    new Intl.NumberFormat(locale, { maximumFractionDigits: index ? 1 : 0 }).format(
      n / 1024 ** index,
    ) +
    ' ' +
    units[index]
  );
}
export const plusDays = (date: string, days: number) =>
  new Date(Date.parse(date + 'T00:00:00Z') + days * 86400000).toISOString().slice(0, 10);
export const betweenDays = (a: string, b: string) =>
  Math.round((Date.parse(b + 'T00:00:00Z') - Date.parse(a + 'T00:00:00Z')) / 86400000);
